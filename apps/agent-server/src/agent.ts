import { agentToolNames, type AgentRequest, type AgentResponse, type AgentToolName, type PageSchema } from "@mpp/schema";
import { agentToolDefinitions, type AgentChatMessage, type AgentToolDefinition } from "./provider";
import { createAgentTools } from "./tools";

export interface AgentToolCall { id: string; name: string; arguments: string; }
export interface AgentModelTurn { content?: string | null; toolCalls?: AgentToolCall[]; }
export interface AgentModelAdapter {
  complete(input: { messages: AgentChatMessage[]; tools: AgentToolDefinition[] }): Promise<AgentModelTurn>;
}

export async function runAgent({ request, model, maxIterations = 8 }: { request: AgentRequest; model: AgentModelAdapter; maxIterations?: number }): Promise<AgentResponse> {
  const executor = createAgentTools(request);
  const trace: AgentResponse["trace"] = [];
  const messages: AgentChatMessage[] = [
    { role: "system", content: `You help create and edit marketing pages through validated proposals.
Call get_current_page before editing. Its current working page is the source of truth, including accepted changes within this request. There is no conversation history from earlier requests.
For existing-page edits, prefer minimal changes using apply_page_changes and exact component IDs. Preserve all unrelated components, props, order, page ID, and title. Never recreate the page to make a small edit.
Use list_components and get_component_definition to discover valid types, defaults, and configurable fields. Use submit_page_layout only for explicit page creation or complete replacement.
For insertion, use beforeComponentId to insert before an existing ID; omit it to append. To insert after a component, use its successor as the anchor, or append if it is last. New IDs are generated by the server; use the page returned by a successful tool or read get_current_page before targeting them.
If multiple components match and the instruction does not identify a target, ask a clarification question and finish without submitting a proposal. Do not choose the first match or change all matches without explicit instruction.
If a tool rejects a batch, none of that batch was applied. Use the indexed validation feedback to correct and retry. Use numbers and booleans with their actual JSON types.
Finish with a concise explanation of the latest accepted proposal. A proposal only updates the editor after the user chooses Apply; never claim it was saved or published.` },
    { role: "user", content: request.instruction }
  ];
  let proposedSchema: PageSchema | null = null;
  for (let iteration = 0; iteration < Math.min(maxIterations, 8); iteration += 1) {
    const turn = await model.complete({ messages, tools: agentToolDefinitions });
    const calls = turn.toolCalls ?? [];
    if (calls.length === 0) {
      return { message: turn.content || (proposedSchema ? "Proposal ready." : "The assistant finished without a valid page proposal."), proposedSchema, trace };
    }

    messages.push({
      role: "assistant",
      content: turn.content ?? null,
      tool_calls: calls.map((call) => ({ id: call.id, type: "function", function: { name: call.name, arguments: call.arguments } }))
    });
    for (const call of calls) {
      let arguments_: unknown;
      try { arguments_ = JSON.parse(call.arguments); } catch { arguments_ = null; }
      const knownTool = (agentToolNames as readonly string[]).includes(call.name);
      const result = !knownTool
        ? {
            success: false,
            observation: { success: false, errors: [`Unknown tool: ${call.name}`] },
            trace: { toolName: call.name, arguments: {}, outcome: "error" as const, summary: "Unknown tool" }
          }
        : arguments_ === null
          ? {
              success: false,
              observation: { success: false, errors: ["Tool arguments must be valid JSON"] },
              trace: { toolName: call.name, arguments: {}, outcome: "error" as const, summary: "Tool arguments must be valid JSON" }
            }
          : executor.execute(call.name as AgentToolName, arguments_);
      trace.push(result.trace);
      if (result.proposedSchema) proposedSchema = result.proposedSchema;
      messages.push({ role: "tool", tool_call_id: call.id, content: JSON.stringify(result.observation) });
    }
  }
  return { message: "The agent reached its maximum of 8 tool iterations without finishing.", proposedSchema: null, trace };
}
